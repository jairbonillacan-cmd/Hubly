const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:3000/dashboard');
  const opener = page.getByRole('button', { name: 'Buscar', exact: true });
  await opener.click();
  const dialog = page.getByRole('dialog', { name: 'Buscar en Hubly' });
  const input = page.getByRole('combobox');
  await expect(input).toBeFocused();
  await page.screenshot({ path: 'e2e/.salida/search-desktop.png' });
  for (let i = 0; i < 15; i++) await input.press('ArrowDown');
  await expect(input).toBeFocused();
  const scroll = await page.locator('.hubly-command-results').evaluate(el => el.scrollTop);
  if (scroll <= 0) throw new Error('Arrow selection did not scroll');
  await input.fill('zzzz sin coincidencias');
  await expect(dialog.getByText('Sin resultados para', { exact: false })).toBeVisible();
  await input.press('Tab');
  await expect(page.getByRole('button', { name: 'Limpiar búsqueda', exact: true }).first()).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(input).toBeFocused();
  await expect(input).toHaveValue('');
  await input.fill('calendario');
  await input.press('Enter');
  await expect(page).toHaveURL(/\/calendario/);
  await page.keyboard.press('Control+k');
  await expect(input).toBeFocused();
  await input.fill('a');
  await input.press('ArrowDown');
  await input.press('Escape');
  await expect(dialog).toHaveCount(0);
  await page.goto('http://localhost:3000/dashboard');
  await opener.click();
  await input.fill('marca');
  await input.press('ArrowDown');
  await input.press('Escape');
  await expect(opener).toBeFocused();
  await opener.click();
  await expect(input).toBeFocused();
  await expect(input).toHaveValue('');
  await input.press('Tab');
  await expect(dialog.getByRole('button', { name: 'Esc Cerrar' })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(dialog).toHaveCount(0);
  await expect(opener).toBeFocused();
  await page.evaluate(() => localStorage.setItem('hubly-theme', 'dark'));
  await page.reload();
  await opener.click();
  await expect(input).toBeFocused();
  await page.screenshot({ path: 'e2e/.salida/search-dark.png' });
  await input.fill('x'.repeat(200));
  await expect(dialog.getByText('Sin resultados para', { exact: false })).toBeVisible();
  await page.screenshot({ path: 'e2e/.salida/search-empty.png' });
  await input.press('Escape');
  await page.evaluate(() => localStorage.setItem('hubly-theme', 'light'));
  await page.setViewportSize({ width: 375, height: 812 });
  await page.reload();
  await page.keyboard.press('Control+k');
  await expect(input).toBeFocused();
  await page.screenshot({ path: 'e2e/.salida/search-mobile.png' });
  const geometry = await dialog.evaluate(el => {
    const r = el.getBoundingClientRect();
    return { x: r.x, right: r.right, bottom: r.bottom, width: innerWidth, height: innerHeight, scrollWidth: el.scrollWidth, clientWidth: el.clientWidth };
  });
  if (geometry.x < 0 || geometry.right > 375 || geometry.bottom > 813 || geometry.scrollWidth > geometry.clientWidth) throw new Error(JSON.stringify(geometry));
  await input.fill('x'.repeat(200));
  await page.screenshot({ path: 'e2e/.salida/search-mobile-empty.png' });
  await input.press('Escape');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(JSON.stringify({ desktop: true, dark: true, mobile: geometry, keyboard: true, empty: true, scroll, errors }));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
